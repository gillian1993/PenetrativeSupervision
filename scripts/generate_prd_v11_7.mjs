const br = '<br>'
const para = '<br><br>'

function productLogic({ structure, interactions, strategy, exception }) {
  return `<strong>页面结构：</strong>${br}${structure.join(br)}${para}<strong>交互逻辑：</strong>${br}${interactions.map((item, index) => `${index + 1}. ${item}`).join(br)}${para}<strong>策略设计：</strong>${br}${strategy.join(br)}${para}<strong>异常处理：</strong>${br}${exception.join(br)}`
}

function row(name, userPath, structure, interactions, strategy, exception, copy, note, priority = 'P0') {
  return `| ${name} | ${userPath} | [图片] | ${productLogic({ structure, interactions, strategy, exception })} | ${copy.join(br)} | ${priority} | 待评审 | ${note} |`
}

