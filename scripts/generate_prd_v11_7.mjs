function section(heading, rows) {
  return `${heading}\n\n以下应用操作按当前工程活动路由、可见页面、真实字段、按钮、状态机和接口边界编写；同一页面内的连续操作合并为一条页面级评审记录。\n\n${[...header, ...rows].join('\n')}\n\n`
}

function replaceSection(content, heading, nextHeading, rows) {
  const start = content.indexOf(heading)
  const end = content.indexOf(nextHeading, start)
  if (start === -1 || end === -1) throw new Error(`Cannot locate section: ${heading}`)
  return content.slice(0, start) + section(heading, rows) + content.slice(end)
}

